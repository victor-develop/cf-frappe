#!/usr/bin/env node
/**
 * Deterministic desk client bundle build.
 *
 * Bundles src/adapters/desk/client-src/main.ts with esbuild (iife, es2022, unminified for
 * readable diffs) and writes BOTH:
 *   - dist/client/desk-client.js                        (raw browser asset)
 *   - src/adapters/desk/client-bundle.generated.ts      (checked-in module exporting the
 *     bundle string + sha256-16 hash, served by the worker after the flip)
 *
 * Determinism: no timestamps, no absolute paths (esbuild path comments are relative to the
 * repo root via absWorkingDir), no minification, LF newlines.
 */

import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

const result = await build({
  absWorkingDir: repoRoot,
  entryPoints: ["src/adapters/desk/client-src/main.ts"],
  bundle: true,
  format: "iife",
  platform: "browser",
  target: "es2022",
  minify: false,
  sourcemap: false,
  legalComments: "none",
  charset: "utf8",
  write: false,
  outfile: "desk-client.js",
  logLevel: "silent"
});

const [output] = result.outputFiles;
if (!output) {
  throw new Error("esbuild produced no output for the desk client bundle");
}

const bundle = output.text.replace(/\r\n/g, "\n");
const hash = createHash("sha256").update(bundle, "utf8").digest("hex").slice(0, 16);

const distAssetPath = join(repoRoot, "dist", "client", "desk-client.js");
mkdirSync(dirname(distAssetPath), { recursive: true });
writeFileSync(distAssetPath, bundle, "utf8");

const generatedPath = join(repoRoot, "src", "adapters", "desk", "client-bundle.generated.ts");
const generated = `// DO NOT EDIT — generated by scripts/build-desk-client.mjs (npm run build:client).
// Source: src/adapters/desk/client-src/. CI guards drift via npm run check:client-fresh.
/* eslint-disable */

export const DESK_CLIENT_BUNDLE_HASH = ${JSON.stringify(hash)};

export const DESK_CLIENT_BUNDLE: string = ${JSON.stringify(bundle)};
`;

const previous = existsSync(generatedPath) ? readFileSync(generatedPath, "utf8") : undefined;
if (previous !== generated) {
  writeFileSync(generatedPath, generated, "utf8");
}

console.log(
  `desk client bundle: ${bundle.length} bytes, sha256-16 ${hash}\n` +
    `  wrote dist/client/desk-client.js\n` +
    `  ${previous === generated ? "unchanged" : "wrote"} src/adapters/desk/client-bundle.generated.ts`
);
